#!/usr/bin/env python3
"""prism.inf: a prismatic bloom. White lily petals with spectral (rainbow) edge dispersion, atom-orbit ellipses,
butterfly-wing ripple contours, on pure black. One slow 'breath' LFO opens the bloom, brightens the pad filter
and widens the reverb; each arp note (onset) flashes the orbits."""
CODE = """
breath = 0.5 + 0.5 * sin(6.2832 * t / 12.0);
flash = 0.0;
orbit = fract(t / 16.0);
p = vec2((uv.x - 0.5) * aspect, uv.y - 0.5) * 0.95;
r = length(p);
a = atan2(p.y, p.x) + t * 0.05 + orbit * 6.2832;
open = 0.55 + 0.45 * breath;
lobe = pow(abs(cos(3.0 * a)), 0.7);
petal = (0.16 + 0.20 * open) * (0.40 + 0.60 * lobe) + 0.015 * sin(12.0 * a + t * 0.5);
curl = 0.008 * sin(a * 9.0 - t * 0.8 + r * 14.0) * open;
d = r - petal - curl;
body = smoothstep(0.012, -0.012, d) * smoothstep(0.0, 0.14, r + 0.04);
core = exp(-r * 14.0) * (0.25 + 0.45 * open);
inner = 0.28 + 0.60 * smoothstep(0.0, petal, r) * (0.6 + 0.4 * lobe);
w = clamp(1.0 - abs(d + 0.012) / (0.060 + 0.040 * open), 0.0, 1.0);
w = w * w;
hue = d * 12.0 + a * 0.30 + t * 0.10;
rb = vec3(0.5 + 0.5 * cos(6.2832 * (hue + 0.0)), 0.5 + 0.5 * cos(6.2832 * (hue + 0.333)), 0.5 + 0.5 * cos(6.2832 * (hue + 0.667)));
rb = pow(rb, vec3(0.8)) * 1.25;
spec = rb * w * (0.85 + 0.5 * flash) * smoothstep(-0.02, 0.01, d + 0.045);
halo = rb * exp(-abs(d) * 10.0) * 0.30 * step(0.0, d);
white = vec3(0.93, 0.94, 0.9) * body * inner;
col = white * 0.8 + spec + halo + vec3(1.0, 0.9, 0.7) * core * 0.6;

@@ORBITS@@
beam = exp(-abs(p.y) * 160.0) * exp(-abs(p.x) * 1.2) * (0.08 + 0.35 * flash);
col = col + vec3(1.0, 0.55, 0.2) * beam;
col = col * (1.0 - smoothstep(0.55, 1.1, r) * 0.6);
"""
ORB = """ph@ = @.0 * 1.0472 + t * 0.07 * (1.0 + @.0) - orbit * 3.0;
ca@ = cos(ph@); sa@ = sin(ph@);
q@ = vec2(p.x * ca@ + p.y * sa@, -p.x * sa@ + p.y * ca@);
e@ = length(vec2(q@.x / (0.62 + 0.08 * open), q@.y / (0.20 + 0.04 * breath)));
de@ = abs(e@ - 1.0);
hue@ = e@ * 2.0 + @.0 * 0.3 + t * 0.15;
rb@ = vec3(0.5 + 0.5 * cos(6.2832 * hue@), 0.5 + 0.5 * cos(6.2832 * (hue@ + 0.333)), 0.5 + 0.5 * cos(6.2832 * (hue@ + 0.667)));
col = col + rb@ * exp(-de@ * 40.0) * 0.6 + vec3(1.0, 0.95, 0.85) * exp(-de@ * 220.0) * 0.35;
"""
CODE = CODE.replace("@@ORBITS@@", "".join(ORB.replace("@", str(k)) for k in range(3)))
out = ["infinite-patch 1", "# Prismatic bloom: lily + atom orbits + spectral dispersion. Generated by art/prism/gen_prism.py"]
n = [0]; wires = []; mods = []
def note(hint, text, w=440, h=150):
    """Comment node placed by tools/patch-layout.py: hint is 'near <id>' or 'band <Picture|Sound|Modulation>'."""
    n[0] += 1; out.append(f"# {hint}\nnode {n[0]} Compositing Comment\n  id c_{hint.split()[-1].lower()}\n  s text {text}\n  f width {w}\n  f height {h}\nend")
def node(cat, typ, nid, body=""):
    n[0] += 1; out.append(f"node {n[0]} {cat} {typ}\n  id {nid}\n{body}end")
node("Source", "FieldPixel", "scene", "  f width 1280\n  f height 1280\n  s code " + " ".join(CODE.split()) + "\n")
node("Effects", "bloom", "glow", "  f uThreshold 0.5\n  f uIntensity 1.1\n  f uRadius 7\n")
node("Compositing", "Trails", "ghost", "  f decay 0.8\n  f zoom 1.003\n  f hueShift 0.004\n  i blendMode 0\n")
node("Effects", "lensdistortion", "lens", "  f uBarrel 0.1\n  f uChroma 0.8\n")
node("Effects", "vignette", "vig", "  f uAmount 0.6\n")
node("Effects", "addnoise", "grain", "  f uAmount 0.025\n")
node("Utility", "Output", "out")

note("band Picture", "PICTURE: a Field Pixel scene draws the lily and three atom orbits from time; the chain to its right adds glow, trails and a rainbow lens fringe. Read left to right.", 900, 110)
note("near scene", "Scene: edit the 'code' text to change the flower. Petals breathe on a 12 s cycle, the same period as the breath LFO below.")
note("near glow", "Bloom: flashes on every arp note (onset) and swells with loudness.")
note("near ghost", "Trails: the low band lengthens the afterimage.")
note("near lens", "Lens: chroma is the rainbow fringe (breath LFO); barrel kicks on each onset.")
note("near out", "Output: picture in, final mix in the audio slot.", 340, 110)
note("band Sound", "SOUND: a slow pad plus a minimal arp. Pad > chorus, arp > delay, both into the mixer > reverb > limiter > Output.", 900, 110)
note("near pad", "Pad: Glass wavetable, 6-voice unison. The breath LFO opens its filter cutoff and wavetable position.", 520, 130)
note("near arp", "Arp: up/down over 2 octaves with a short gate. Feeds the pluck; its notes create the onset that flashes the picture.")
note("near hall", "Reverb: mix swells with the breath LFO.", 440, 110)
note("band Modulation", "MODULATION: the breath LFO (12 s) opens the pad filter, reverb, delay feedback and lens chroma. Audio Analyze listens to the final mix and drives the picture.", 900, 110)
note("near ana", "Audio Analyze: level, bands and onset of the final mix. They drive bloom, lens and trails.", 460, 130)
note("near breathlfo", "Breath LFO: one slow sine shared by sound and picture.", 420, 110)
wires += ["cable glow 0 scene", "cable ghost 0 glow", "cable lens 0 ghost", "cable vig 0 lens", "cable grain 0 vig", "cable out 0 grain"]
# sound: pad (slow minor-pentatonic-ish) + minimal arp
node("Notes", "Random Note Generator", "padnotes", "  i rangeLow 50\n  i rangeHigh 62\n  i scale 10\n  i root 2\n  f rateBeats 4\n  i maxStep 2\n")
node("Notes", "Random Note Generator", "arpseed", "  i rangeLow 62\n  i rangeHigh 74\n  i scale 10\n  i root 2\n  f rateBeats 8\n  i maxStep 2\n")
node("Notes", "Arpeggiator", "arp", "  i mode 2\n  i octaves 2\n  f gatePercent 45\n")
node("Synths", "Wavetable", "pad", "  f volume 0.7\n  i a.table 11\n  i a.unison 6\n  f a.detune 20\n  f a.stereoWidth 0.9\n  f a.ampAttack 1800\n  f a.ampRelease 3500\n  f a.ampSustain 0.9\n  i a.filterType 2\n  f a.cutoff 1500\n  f a.resonance 0.2\n")
node("Synths", "Wavetable", "pluck", "  f volume 0.45\n  i a.table 6\n  f a.ampAttack 3\n  f a.ampDecay 700\n  f a.ampSustain 0\n  f a.ampRelease 900\n  i a.filterType 2\n  f a.cutoff 6000\n")
node("AudioEffects", "Chorus", "padchorus", "  f mix 0.4\n  f rate 0.25\n")
node("AudioEffects", "Delay", "arpdelay", "  f mix 0.45\n  f feedback 52\n  f tone -0.3\n")
node("Utility", "Mixer", "mix")
node("AudioEffects", "Reverb", "hall", "  f mix 0.4\n  f size 0.85\n  f decay 7\n")
node("AudioEffects", "Limiter", "lim")
node("Modulators", "Audio Analyze", "ana", "  f gain 2.0\n  f attack 0.3\n  f release 0.45\n")
node("Modulators", "LFO", "breathlfo", "  i shape 0\n  f rateBeats 24\n")
wires += ["note pad 0 padnotes", "note arp 0 arpseed", "note pluck 0 arp", "aud padchorus 0 pad", "aud arpdelay 0 pluck",
          "aud mix 0 padchorus", "aud mix 1 arpdelay", "aud hall 0 mix", "aud lim 0 hall", "aud out 1 lim", "aud ana 0 lim"]
def M(dst, key, src, o, lo, hi, pol=0):
    mods.append(f"mod {dst} {key} {src} {o} {pol} 1 0.5 {lo} {hi}")
M("lens", "uBarrel", "ana", 4, 0.1, 0.35)
M("glow", "uThreshold", "ana", 4, 0.5, 0.25)
M("glow", "uIntensity", "ana", 0, 0.9, 2.0)
M("lens", "uChroma", "breathlfo", 0, 0.4, 1.8)
M("ghost", "decay", "ana", 1, 0.55, 0.85)
M("pad", "a.cutoff", "breathlfo", 0, 700, 6500)
M("pad", "a.position", "breathlfo", 0, 0.1, 0.9)
M("hall", "mix", "breathlfo", 0, 0.25, 0.6)
M("arpdelay", "feedback", "breathlfo", 0, 35, 70)
M("pluck", "a.cutoff", "ana", 2, 2500, 9000)
open("prism.inf", "w").write("\n".join(out + wires + mods) + "\n")
import subprocess, pathlib
subprocess.check_call(["python3", str(pathlib.Path(__file__).resolve().parents[2] / "tools/patch-layout.py"), "prism.inf"])
